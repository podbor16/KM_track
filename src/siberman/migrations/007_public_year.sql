-- Какой год показывать на ПУБЛИЧНОЙ странице результатов — независимо от
-- того, какой год последним загружали в админке (2026-08-05: до этого
-- публичная страница брала MAX(race_year), что работало, пока в БД был
-- только один год; с появлением тестовой страницы /siberman/test и
-- тестовых данных под будущими годами это стало течь на прод).
-- Ровно одна строка с is_public=1 в любой момент — публичная переключается
-- явно через set_public_race_year(), а не автоматически по номеру года.
ALTER TABLE race_config
  ADD COLUMN is_public TINYINT(1) NOT NULL DEFAULT 0;

-- Сохраняем текущее поведение: год, который уже был последним (и,
-- соответственно, показывался на публичной странице до этой миграции),
-- помечаем публичным, чтобы ничего не переключилось незаметно.
UPDATE race_config SET is_public = 1
WHERE race_year = (SELECT race_year FROM (SELECT MAX(race_year) AS race_year FROM race_config) t);
