def _norm_person_name(surname: str, name: str) -> str:
    return " ".join(f"{surname} {name}".split()).lower()


def get_finish_count(
    surname: str,
    name: str,
    race_year: int,
    finished_years_by_name: dict[str, set[int]],
) -> int:
    """Сколько раз участник финишировал ДО race_year: базовое (до-БД,
    условно "до 2025") число + сколько лет из БД (2025 и позже),
    СТРОГО МЕНЬШЕ race_year, есть в finished_years_by_name для этого
    имени (см. db.get_finished_years_by_name — годы, где participants
    с этим именем реально дошли до финиша бега)."""
    key = _norm_person_name(surname, name)
    baseline = BASELINE_PRE_DB_FINISH_COUNTS.get(key, 0)
    db_years = finished_years_by_name.get(key, ())
    dynamic = sum(1 for y in db_years if y < race_year)
    return baseline + dynamic
