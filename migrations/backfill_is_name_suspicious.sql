-- Пересчёт is_name_suspicious для ВСЕХ строк leads по актуальному критерию
-- (только кириллица + дефис — иначе подозрительно), тем же, что используют
-- tilda_webhook.is_name_suspicious() / bulk_import_leads() / update_lead().
--
-- До этой миграции флаг был неверным по трём независимым причинам (все
-- исправлены в коде, коммиты b3dea19/af0775c):
-- 1. bulk_import_leads() всегда хардкодил 0 при вставке новой заявки —
--    флаг никогда не считался для CSV-импорта.
-- 2. update_lead() (ручная правка ФИО в админке) не пересчитывал флаг при
--    смене surname/name — застревал на значении со времени вставки.
-- 3. order_id=0 — заглушка Tilda для бесплатных/незавершённых заявок, не
--    настоящий номер заказа (не влияет на сам флаг, но подтверждает общую
--    картину "лид редактировался/переимпортировался после первой вставки").
--
-- order_id=0 сам по себе к этой миграции не относится — здесь просто
-- признак: у большого числа лидов ФИО/данные менялись уже после вставки,
-- поэтому исходный is_name_suspicious давно разошёлся с реальностью.
-- 2026-08-17

UPDATE leads
SET is_name_suspicious = (
  (surname != '' AND surname NOT REGEXP '^[а-яёА-ЯЁ-]+$')
  OR (name != '' AND name NOT REGEXP '^[а-яёА-ЯЁ-]+$')
);
