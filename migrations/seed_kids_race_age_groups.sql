-- 2026-08-19) — заменяет дефолтные "взрослые" границы, засеянные
-- предыдущей миграцией (create_age_group_configs.sql) общей формулой
-- calculate_age_group(), для детского забега бессмысленной (никакого
-- "Ж75+" на дистанции для детей 6-11 лет не будет).
--
-- Категории только по возрасту, БЕЗ деления по полу — расписание волн
-- старта организовано строго по году рождения, не по полу. Схема
-- age_group_configs требует sex NOT NULL (см. миграцию create_..), других
-- способов задать "без деления по полу" нет — одинаковый label для M и F.
--
-- Границы заданы ВОЗРАСТОМ (min_age=max_age=N), а не годом рождения —
-- get_age_group_label() сравнивает по возрасту на текущий момент
-- (age = текущий_год - год_рождения, тот же календарный расчёт, что
-- _parse_age_and_sex()), поэтому эта же настройка остаётся корректной
-- для детского забега ЛЮБОГО следующего года без правки: в 2027 году
-- ребёнок 2016 г.р. будет уже не "10 лет", а "11 лет" — и попадёт в
-- нужный брекет автоматически, никакой миграции на новый год не нужно.
--
-- "500 м" в реальной схеме НЕ разбита по возрасту вообще (дистанция для
-- самых маленьких без соревновательных категорий) — дефолтные границы
-- для неё тоже удалены, тот же принцип, что у "2 км" Жары (см.
-- seed_zhara_real_age_groups.sql) — категория там будет пустой строкой,
-- фильтр/колонка скрыты целиком.
-- 2026-08-19

