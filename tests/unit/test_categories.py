"""Единый краткий вид категорий результатов (src/common/categories.py) — на реальных
написаниях из БД (срез 2026-10-06)."""
import pytest

from src.common.categories import age_category, canonical_category


@pytest.mark.parametrize("raw, canon", [
    ("мужчины до 49 лет (1976 г.р. и младше)", "М49"),
    ("женщины до 49 лет", "Ж49"),
    ("М 49", "М49"),
    ("Ж 12-49", "Ж12-49"),
    ("М12-49", "М12-49"),
    ("женщины 50-59 лет (1966-1975 г.р.)", "Ж50-59"),
    ("мужчины 60-64 года (1961-1965 г.р.)", "М60-64"),
    ("женщины 65 лет и старше (1960 г.р. и старше)", "Ж65+"),
    ("мужчины 75 лет и старше (1952-1956 г.р.)", "М75+"),        # годы в скобках у Copernico ошибочны
    ("женщины 60 лет и старше (1964 г.р. и старше)", "Ж60+"),
    ("М 80+", "М80+"),
    ("Ж65+", "Ж65+"),
    ("М35-39", "М35-39"),
    ("Ж 50-59", "Ж50-59"),
    ("Мальчики 2015 г.р.", "Мальчики 2015 г.р."),
    ("девочки 2016 г. р.", "Девочки 2016 г.р."),
    ("Женщины", "Женщины"),
    ("Мужчины", "Мужчины"),
    ("Unknown", "Unknown"),
    ("", ""),
    (None, ""),
])
def test_canonical_category(raw, canon):
    assert canonical_category(raw) == canon


def test_canonical_is_idempotent():
    for raw in ("мужчины до 49 лет (1976 г.р. и младше)", "Ж 65-69", "Мальчики 2015 г.р."):
        assert canonical_category(canonical_category(raw)) == canonical_category(raw)


def test_age_category_women7_groups():
    assert [age_category("Ж", a) for a in (18, 49, 50, 59, 60, 64, 65, 69, 74, 79, 80)] == \
        ["Ж49", "Ж49", "Ж50-59", "Ж50-59", "Ж60-64", "Ж60-64", "Ж65-69", "Ж65-69", "Ж70-74", "Ж75-79", "Ж80+"]
